def write_capture(path: Path, seconds: float = 0.2, rate: float = 2_000_000.0) -> Path:
    """A small cs8 capture with a tone in it, standing in for a wideband recording."""
    samples = int(seconds * rate)
    t = np.arange(samples) / rate
    tone = 0.4 * np.exp(2j * np.pi * (446_093_750.0 - 446_593_750.0) * t)
    noise = 0.02 * (np.random.default_rng(0).standard_normal(samples) * (1 + 1j))
    iq = (tone + noise).astype(np.complex64)
    np.clip(iq.view(np.float32) * 127, -127, 127).astype(np.int8).tofile(path)
    return path


def test_the_extractor_cuts_shifts_and_decimates(tmp_path: Path) -> None:
    capture = write_capture(tmp_path / "capture.cs8")

    samples = extract_vector.extract(
        source_path=capture,
        start_s=0.0,
        duration_s=0.1,
        source_centre_hz=446_593_750.0,
        source_rate_hz=2_000_000.0,
        source_format="cs8",
    )

    assert samples.dtype == np.complex64
    assert len(samples) == pytest.approx(0.1 * extract_vector.VECTOR_SAMPLE_RATE_HZ, rel=0.02)


def test_the_extractor_removes_the_receivers_dc_offset(tmp_path: Path) -> None:
    """Skipping this aliases the local-oscillator spur onto a channel when decimating."""
    capture = write_capture(tmp_path / "capture.cs8")

    samples = extract_vector.extract(
        source_path=capture,
        start_s=0.0,
        duration_s=0.1,
        source_centre_hz=446_593_750.0,
        source_rate_hz=2_000_000.0,
        source_format="cs8",
    )

    assert abs(complex(samples.mean())) < 0.05


def test_the_extractor_refuses_a_span_the_file_does_not_hold(tmp_path: Path) -> None:
    capture = write_capture(tmp_path / "capture.cs8", seconds=0.05)

    with pytest.raises(ValueError, match="holds"):
        extract_vector.extract(
            source_path=capture,
            start_s=0.0,
            duration_s=10.0,
            source_centre_hz=446_593_750.0,
            source_rate_hz=2_000_000.0,
            source_format="cs8",
        )


def test_the_extractor_refuses_a_non_integer_decimation(tmp_path: Path) -> None:
    capture = write_capture(tmp_path / "capture.cs8")

    with pytest.raises(ValueError, match="integer decimation"):
        extract_vector.extract(
            source_path=capture,
            start_s=0.0,
            duration_s=0.05,
            source_centre_hz=446_593_750.0,
            source_rate_hz=1_234_567.0,
            source_format="cs8",
            target_rate_hz=500_000.0,
        )


def test_the_extractor_writes_a_vector_beside_its_description(tmp_path: Path) -> None:
    """The sidecar is what lets a replayed vector report when the signal happened."""
    samples = (np.arange(1000) / 1000).astype(np.float32).view(np.complex64)

    iq_path, metadata_path = extract_vector.write_vector(
        samples, tmp_path / "vector", {"note": "unit test", "start_time": 1.0}
    )

    assert iq_path.suffix == ".cs8"
    payload = json.loads(metadata_path.read_text())
    assert payload["note"] == "unit test"
    assert payload["scale_peak"] > 0


def test_the_extractor_normalises_before_quantising(tmp_path: Path) -> None:
    """Writing a weak extract without scaling buries it in the bottom few codes of cs8.

    Checked on the magnitude rather than on either component: a sample at 45 degrees puts
    127/sqrt(2) = 90 in each of I and Q while still being full scale, so a per-component
    threshold would measure the signal's phase as much as its level.
    """
    weak = (1e-4 * np.ones(1000, dtype=np.float32)).view(np.complex64)

    iq_path, _ = extract_vector.write_vector(weak, tmp_path / "vector", {})

    written = np.fromfile(iq_path, dtype=np.int8).astype(np.float32).view(np.complex64)
    assert np.abs(written).max() > 120
