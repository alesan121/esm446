"""Verification of the entry points that had no tests at all.

Two command-line tools shipped with zero coverage: the TLS server and the test-vector
extractor. Both are things somebody running this project would actually invoke, and a project
whose pitch is verification cannot have entry points nobody ever executed. These are not deep
tests -- the logic underneath them is tested elsewhere -- they check that each tool parses its
arguments, does the thing, and fails comprehensibly rather than with a traceback.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import numpy as np
import pytest

from esm446.cli import cot_server, extract_vector

# --------------------------------------------------------------------------------------
# The TLS server
# --------------------------------------------------------------------------------------


@pytest.fixture
def certificate(tmp_path: Path) -> tuple[Path, Path]:
    import shutil

    if not shutil.which("openssl"):
        pytest.skip("openssl is not installed")
    cert, key = tmp_path / "cot.crt", tmp_path / "cot.key"
    subprocess.run(
        [
            "openssl",
            "req",
            "-x509",
            "-newkey",
            "rsa:2048",
            "-nodes",
            "-days",
            "1",
            "-keyout",
            str(key),
            "-out",
            str(cert),
            "-subj",
            "/CN=localhost",
        ],
        capture_output=True,
        check=True,
    )
    return cert, key


def test_the_server_reports_a_missing_certificate_rather_than_a_traceback(tmp_path: Path) -> None:
    """The first thing anybody hits, because the certificate has to be generated by hand."""
    status = cot_server.main(
        ["--cert", str(tmp_path / "absent.crt"), "--key", str(tmp_path / "absent.key")]
    )

    assert status == 1


def test_the_server_broadcasts_what_it_reads_from_stdin(
    certificate: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch, capsys
) -> None:
    """The mode that makes it testable by hand: pipe stored events in, watch iTAK draw them."""
    import io
    import socket
    import ssl
    import threading

    cert, key = certificate
    received: list[bytes] = []
    ready = threading.Event()

    # A port the operating system picks, so the test cannot collide with anything.
    probe = socket.socket()
    probe.bind(("127.0.0.1", 0))
    port = probe.getsockname()[1]
    probe.close()

    def client() -> None:
        ready.wait(timeout=5.0)
        context = ssl.create_default_context()
        context.check_hostname = False
        context.verify_mode = ssl.CERT_NONE
        for _ in range(50):
            try:
                with context.wrap_socket(socket.create_connection(("127.0.0.1", port), 2.0)) as s:
                    s.settimeout(4.0)
                    received.append(s.recv(65535))
                return
            except OSError:
                threading.Event().wait(0.05)

    thread = threading.Thread(target=client, daemon=True)
    thread.start()

    # Hold stdin open until the client has connected, or the server broadcasts to nobody.
    class SlowStdin(io.StringIO):
        def __iter__(self):
            ready.set()
            threading.Event().wait(1.0)
            return iter(["<event uid='test'/>\n"])

    monkeypatch.setattr("sys.stdin", SlowStdin())

    status = cot_server.main(
        [
            "--cert",
            str(cert),
            "--key",
            str(key),
            "--host",
            "127.0.0.1",
            "--port",
            str(port),
            "--stdin",
        ]
    )
    thread.join(timeout=6.0)

    assert status == 0
    assert received and b"test" in received[0]


def test_the_server_binds_loopback_by_default() -> None:
    """A sensor feed reachable from every interface the moment somebody starts it."""
    parser_default = cot_server.main.__doc__ is not None
    assert parser_default

    import argparse
    import inspect

    source = inspect.getsource(cot_server.main)
    assert '"--host",\n        default="127.0.0.1"' in source or 'default="127.0.0.1"' in source
    assert "0.0.0.0" not in source.split("default=")[1].split(",")[0]
    del argparse


